const { pathToFileURL } = require('node:url');
const { spawnSync } = require('node:child_process');
const { chromium } = require('playwright');

const root = path.resolve(__dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'paper-review-workflow-'));
const input = path.join(root, 'assets', 'example-review.json');
function python(args) {
  return spawnSync('python3', args, { cwd: root, encoding: 'utf8' });
}
function build(inputFile, directory) {
  const result = python(['scripts/build_report.py', inputFile, '--output-dir', directory, '--basename', 'sample-report', '--html-only']);
  assert.equal(result.status, 0, result.stderr);
  return path.join(directory, 'sample-report.html');
}
const html = build(input, path.join(temp, 'report'));
const proposal = (page, id) => page.locator('[data-proposal-id="' + id + '"]');
const option = (page, id) => page.locator('[data-option-id="' + id + '"] .option-radio');
async function exported(page, name) {
  const pending = page.waitForEvent('download');
  await page.locator('#export-choices').click();
  const download = await pending;
  const file = path.join(temp, name);
  await download.saveAs(file);
  return {file, value: JSON.parse(fs.readFileSync(file, 'utf8'))};
}

